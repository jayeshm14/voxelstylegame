/**
 * Simplex noise and fractal Brownian motion over a seeded permutation.
 *
 * `contracts/world-generation.md` fixes the algorithm as a breaking commitment:
 *
 * - a **256-entry permutation** produced by Fisher–Yates driven by
 *   `mulberry32(hash32(seed, SALT.NOISE))`
 * - **simplex 2D and 3D**
 * - **fBm** with lacunarity 2.0, gain 0.5
 * - output in `[-1, 1]`
 *
 * ## No trigonometry, and no `Math.sqrt` either (research R4, contract D4)
 *
 * D4 restricts generation maths to `+ - * /`, `Math.imul`, shifts, comparisons
 * and `Math.floor`. Simplex normally reaches for `Math.sqrt(3)` to build its
 * skew constants and again to normalise its gradient vectors; both are avoided
 * here:
 *
 * - the skew constants are written as literals computed once from a literal
 *   `SQRT3`, using only subtraction, multiplication and division;
 * - the gradient tables are **unit vectors written out in full**, so the
 *   `1/√2` that appears in them is a literal too.
 *
 * Nothing in this module evaluates a square root or a trig function at run
 * time. `tests/chunk-purity.test.ts` asserts that by reading the source, because
 * a determinism rule that depends on someone remembering it is not a rule.
 *
 * ## Why the noise is an instance and not module state
 *
 * The permutation depends on the seed, and `generateChunk` may not read
 * module-level state (Principle I). So the table is built once per
 * {@link SimplexNoise} construction and lives in that object's fields;
 * `generateChunk` constructs one locally from its own `seed` argument. Nothing
 * is shared between calls, which is what makes two calls with the same
 * arguments byte-identical regardless of what ran in between.
 *
 * Constitution test areas: *seed determinism*, *purity*.
 */

import { SALT, hash32, type Salt } from '../utils/Hash'
import { mulberry32 } from '../utils/Prng'
import { NOISE } from '../core/GameConfig'

/**
 * Skew factor for the 2D simplex lattice: `F2 = (√3 − 1) / 2`.
 * Written as an expression over a literal `SQRT3` so no `Math.sqrt` appears.
 */
const SQRT3 = 1.7320508075688772
const F2 = 0.5 * (SQRT3 - 1)
const G2 = (3 - SQRT3) / 6

/** Unskew factor for the 3D simplex lattice. */
const F3 = 1 / 3
const G3 = 1 / 6

/**
 * `1/√2`, written out. Every gradient below is either a unit axis vector or a
 * pair of these, so each table entry has length exactly 1 without a run-time
 * square root.
 */
const INV_SQRT2 = 0.7071067811865476

/** Eight unit directions in the plane: four axes and four diagonals. */
const GRAD2 = Object.freeze([
  1, 0, -1, 0, 0, 1, 0, -1, INV_SQRT2, INV_SQRT2, -INV_SQRT2, INV_SQRT2, INV_SQRT2,
  -INV_SQRT2, -INV_SQRT2, -INV_SQRT2,
])

/** Twelve unit directions: the edge midpoints of a cube, for 3D. */
const GRAD3 = Object.freeze([
  INV_SQRT2, INV_SQRT2, 0, -INV_SQRT2, INV_SQRT2, 0, INV_SQRT2, -INV_SQRT2, 0,
  -INV_SQRT2, -INV_SQRT2, 0, INV_SQRT2, 0, INV_SQRT2, -INV_SQRT2, 0, INV_SQRT2,
  INV_SQRT2, 0, -INV_SQRT2, -INV_SQRT2, 0, -INV_SQRT2, 0, INV_SQRT2, INV_SQRT2,
  0, -INV_SQRT2, INV_SQRT2, 0, INV_SQRT2, -INV_SQRT2, 0, -INV_SQRT2, -INV_SQRT2,
])

/**
 * Output scales, set from a dense measurement of the raw sums rather than from
 * the classic `70` / `32` constants — see `docs/TECHNICAL_DECISIONS.md` TD-018.
 *
 * With unit-length gradients (instead of the classic non-unit `grad3` table) the
 * raw extrema measure **0.010080** in 2D and **0.021625** in 3D, and both are
 * identical across seeds: the bound comes from the lattice geometry and the
 * gradient set, not from the permutation. Multiplying by 90 and 40 puts the
 * observed peaks at 0.907 and 0.865 — inside `[-1, 1]` with roughly 10% headroom
 * for a peak the grid missed — and {@link clampUnit} holds the contract
 * regardless of where a peak actually falls, so no seed can escape the interval.
 *
 * They are algorithm constants rather than tunables: lacunarity and gain are the
 * fBm knobs and live in `GameConfig`, whereas changing a scale would change
 * every generated byte and therefore invalidate the committed golden hash.
 */
const SCALE_2D = 90
const SCALE_3D = 40

/**
 * Seeded simplex noise.
 *
 * Construct one per consumer (Principle I): the permutation is derived from the
 * seed, so two instances with different seeds are independent streams and two
 * instances with the same seed agree exactly.
 */
export class SimplexNoise {
  /** 256-entry Fisher–Yates permutation of `0…255`. */
  readonly #perm: Uint8Array
  /** 512-entry wrap table, so indexing needs one `& 255` instead of two. */
  readonly #perm512: Uint8Array

  /**
   * @param seed int32 world seed
   * @param salt which subsystem this instance serves — `SALT.NOISE` by default,
   *        which makes the default construction exactly the permutation
   *        `contracts/world-generation.md` commits to:
   *        `mulberry32(hash32(seed, SALT_NOISE))`.
   *
   * Pass a different closed salt to get an **independent permutation** for a
   * subsystem that needs its own field (climate, caves, ores). That is what D2's
   * *"each consumer derives its own stream"* means here: the permutation is
   * immutable once built and each instance owns its own, so two fields can
   * never advance each other, and the salt keeps their streams from ever
   * colliding.
   */
  constructor(seed: number, salt: Salt = SALT.NOISE) {
    const perm = new Uint8Array(256)
    for (let i = 0; i < 256; i++) perm[i] = i

    const rng = mulberry32(hash32(seed, salt))
    // Fisher–Yates, descending, swapping each slot with a uniformly chosen one
    // at or below it. Every value stays in 0…255 by construction.
    for (let i = 255; i > 0; i--) {
      const j = rng.nextInt(i + 1)
      const atI = perm[i] as number
      perm[i] = perm[j] as number
      perm[j] = atI
    }

    const perm512 = new Uint8Array(512)
    for (let i = 0; i < 512; i++) perm512[i] = perm[i & 255] as number
    this.#perm = perm
    this.#perm512 = perm512
  }

  /** Hash of the lattice point `(x, y)`, in `0 … 255`. */
  #h2(x: number, y: number): number {
    const p = this.#perm512
    return p[(p[x & 255] as number) + (y & 255)] as number
  }

  /** Hash of the lattice point `(x, y, z)`, in `0 … 255`. */
  #h3(x: number, y: number, z: number): number {
    const p = this.#perm512
    return p[(p[(p[x & 255] as number) + (y & 255)] as number) + (z & 255)] as number
  }

  /**
   * Simplex noise in the plane, in `[-1, 1]`.
   *
   * Skews the input onto a simplex lattice, finds the enclosing simplex by
   * comparing `x0` against `y0`, then sums a radial falloff weighted by the
   * corner gradient. The falloff `0.6 − r²` (the 3D form) and `0.5 − r²` (2D)
   * are polynomials, so the whole path stays inside D4's allowed operations.
   */
  noise2D(xin: number, yin: number): number {
    const skew = (xin + yin) * F2
    const i = Math.floor(xin + skew)
    const j = Math.floor(yin + skew)
    const unskew = (i + j) * G2
    const x0 = xin - (i - unskew)
    const y0 = yin - (j - unskew)

    const i1 = x0 > y0 ? 1 : 0
    const j1 = 1 - i1

    const x1 = x0 - i1 + G2
    const y1 = y0 - j1 + G2
    const x2 = x0 - 1 + 2 * G2
    const y2 = y0 - 1 + 2 * G2

    const ii = i & 255
    const jj = j & 255
    const g0 = (this.#h2(ii, jj) & 7) * 2
    const g1 = (this.#h2(ii + i1, jj + j1) & 7) * 2
    const g2 = (this.#h2(ii + 1, jj + 1) & 7) * 2

    let n0 = 0
    let n1 = 0
    let n2 = 0

    let t0 = 0.5 - x0 * x0 - y0 * y0
    if (t0 > 0) {
      t0 *= t0
      n0 = t0 * t0 * ((GRAD2[g0] as number) * x0 + (GRAD2[g0 + 1] as number) * y0)
    }
    let t1 = 0.5 - x1 * x1 - y1 * y1
    if (t1 > 0) {
      t1 *= t1
      n1 = t1 * t1 * ((GRAD2[g1] as number) * x1 + (GRAD2[g1 + 1] as number) * y1)
    }
    let t2 = 0.5 - x2 * x2 - y2 * y2
    if (t2 > 0) {
      t2 *= t2
      n2 = t2 * t2 * ((GRAD2[g2] as number) * x2 + (GRAD2[g2 + 1] as number) * y2)
    }

    return clampUnit(SCALE_2D * (n0 + n1 + n2))
  }

  /**
   * Simplex noise in three dimensions, in `[-1, 1]`.
   *
   * The tetrahedral split below is a sequence of comparisons only — no
   * division by a coordinate, no square root — so which cell a point falls in
   * is decided by exactly the operations D4 allows.
   */
  noise3D(xin: number, yin: number, zin: number): number {
    const skew = (xin + yin + zin) * F3
    const i = Math.floor(xin + skew)
    const j = Math.floor(yin + skew)
    const k = Math.floor(zin + skew)
    const unskew = (i + j + k) * G3
    const x0 = xin - (i - unskew)
    const y0 = yin - (j - unskew)
    const z0 = zin - (k - unskew)

    let i1: number
    let j1: number
    let k1: number
    let i2: number
    let j2: number
    let k2: number

    if (x0 >= y0) {
      if (y0 >= z0) {
        i1 = 1; j1 = 0; k1 = 0; i2 = 1; j2 = 1; k2 = 0
      } else if (x0 >= z0) {
        i1 = 1; j1 = 0; k1 = 0; i2 = 1; j2 = 0; k2 = 1
      } else {
        i1 = 0; j1 = 0; k1 = 1; i2 = 1; j2 = 0; k2 = 1
      }
    } else if (y0 < z0) {
      i1 = 0; j1 = 0; k1 = 1; i2 = 0; j2 = 1; k2 = 1
    } else if (x0 < z0) {
      i1 = 0; j1 = 1; k1 = 0; i2 = 0; j2 = 1; k2 = 1
    } else {
      i1 = 0; j1 = 1; k1 = 0; i2 = 1; j2 = 1; k2 = 0
    }

    const x1 = x0 - i1 + G3
    const y1 = y0 - j1 + G3
    const z1 = z0 - k1 + G3
    const x2 = x0 - i2 + 2 * G3
    const y2 = y0 - j2 + 2 * G3
    const z2 = z0 - k2 + 2 * G3
    const x3 = x0 - 1 + 3 * G3
    const y3 = y0 - 1 + 3 * G3
    const z3 = z0 - 1 + 3 * G3

    const ii = i & 255
    const jj = j & 255
    const kk = k & 255
    const g0 = (this.#h3(ii, jj, kk) % 12) * 3
    const g1 = (this.#h3(ii + i1, jj + j1, kk + k1) % 12) * 3
    const g2 = (this.#h3(ii + i2, jj + j2, kk + k2) % 12) * 3
    const g3 = (this.#h3(ii + 1, jj + 1, kk + 1) % 12) * 3

    let n0 = 0
    let n1 = 0
    let n2 = 0
    let n3 = 0

    let t0 = 0.6 - x0 * x0 - y0 * y0 - z0 * z0
    if (t0 > 0) {
      t0 *= t0
      n0 = t0 * t0 * (dot3(GRAD3, g0, x0, y0, z0))
    }
    let t1 = 0.6 - x1 * x1 - y1 * y1 - z1 * z1
    if (t1 > 0) {
      t1 *= t1
      n1 = t1 * t1 * (dot3(GRAD3, g1, x1, y1, z1))
    }
    let t2 = 0.6 - x2 * x2 - y2 * y2 - z2 * z2
    if (t2 > 0) {
      t2 *= t2
      n2 = t2 * t2 * (dot3(GRAD3, g2, x2, y2, z2))
    }
    let t3 = 0.6 - x3 * x3 - y3 * y3 - z3 * z3
    if (t3 > 0) {
      t3 *= t3
      n3 = t3 * t3 * (dot3(GRAD3, g3, x3, y3, z3))
    }

    return clampUnit(SCALE_3D * (n0 + n1 + n2 + n3))
  }

  /**
   * Fractal Brownian motion in the plane: octaves of {@link noise2D} at
   * `LACUNARITY` × frequency and `GAIN` × amplitude, divided by the summed
   * amplitude so the result stays in `[-1, 1]`.
   *
   * The normaliser is accumulated in the same loop rather than computed from a
   * closed-form geometric series, so it is always exactly the sum of the
   * amplitudes actually used — including when `octaves` is not a power of two.
   */
  fbm2D(x: number, y: number, octaves: number = NOISE.OCTAVES): number {
    let sum = 0
    let amplitude = 1
    let frequency = 1
    let normaliser = 0
    for (let o = 0; o < octaves; o++) {
      sum += amplitude * this.noise2D(x * frequency, y * frequency)
      normaliser += amplitude
      amplitude *= NOISE.GAIN
      frequency *= NOISE.LACUNARITY
    }
    if (normaliser === 0) return 0
    return clampUnit(sum / normaliser)
  }

  /** {@link fbm2D} in three dimensions. */
  fbm3D(x: number, y: number, z: number, octaves: number = NOISE.OCTAVES): number {
    let sum = 0
    let amplitude = 1
    let frequency = 1
    let normaliser = 0
    for (let o = 0; o < octaves; o++) {
      sum += amplitude * this.noise3D(x * frequency, y * frequency, z * frequency)
      normaliser += amplitude
      amplitude *= NOISE.GAIN
      frequency *= NOISE.LACUNARITY
    }
    if (normaliser === 0) return 0
    return clampUnit(sum / normaliser)
  }
}

/** Dot a gradient triple against a vector. */
function dot3(table: readonly number[], offset: number, x: number, y: number, z: number): number {
  return (
    (table[offset] as number) * x +
    (table[offset + 1] as number) * y +
    (table[offset + 2] as number) * z
  )
}

/**
 * Clamp to `[-1, 1]`.
 *
 * The contract says noise output is *in* `[-1, 1]`, and floating-point
 * accumulation can land a hair outside whatever scale is chosen for a
 * particular permutation. The comparison is exact and branch-free of any
 * rounding decision, so the bound holds for every seed rather than for the one
 * the scale was measured against — and it keeps fBm's normalised sum inside the
 * same interval no matter how many octaves are requested.
 */
function clampUnit(value: number): number {
  if (value > 1) return 1
  if (value < -1) return -1
  return value
}
